#!/usr/bin/env python3
"""SessionStart hook: brief Claude on where it is. Stdout becomes session context.

Prints the branch, the authorised increment, protected-path state, the latest verification report and
whether it describes this tree, and the open-question count. Facts only, computed now.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[2])
sys.path.insert(0, str(ROOT / "tools"))


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], capture_output=True, text=True).stdout.strip()


def main() -> int:
    lines = ["## ReArchive session briefing (generated by .claude/hooks/session_start.py)"]
    status = ROOT / "docs" / "STATUS.md"
    text = status.read_text(encoding="utf-8") if status.exists() else ""
    phase = re.search(r"^\*\*Current phase:\*\*\s*(.+)$", text, re.MULTILINE)
    inc = re.search(r"^\*\*Current increment:\*\*\s*(\S+)", text, re.MULTILINE)
    increment = inc.group(1) if inc else "UNKNOWN"
    branch = git("branch", "--show-current") or "(detached)"
    head = git("rev-parse", "--short=12", "HEAD") or "(no commits)"
    dirty = [line for line in git("status", "--porcelain").splitlines() if line]

    lines.append(f"- Phase: {phase.group(1).strip() if phase else 'UNKNOWN'}; authorised increment: **{increment}**")
    lines.append(f"- Branch `{branch}` at `{head}`; {len(dirty)} uncommitted change(s)")
    expected = f"inc/{increment}"
    if branch in ("main", "master"):
        lines.append(
            f"- WARNING: on {branch}. Do not edit. Ask the owner to create `{expected}` (`git switch -c {expected}`)."
        )
    elif not branch.startswith(expected):
        lines.append(f"- WARNING: branch is not `{expected}`; confirm with the owner before working.")

    try:
        import protected_paths

        result = protected_paths.check(ROOT)
        lines.append(
            "- Protected paths: clean against `" + str(result.base) + "`"
            if result.clean
            else "- Protected paths: DIFFER from baseline — stop and tell the owner:\n  "
            + protected_paths.describe(result).replace("\n", "\n  ")
        )
    except Exception as exc:
        lines.append(f"- Protected paths: could not check ({exc})")

    latest = ROOT / "reports" / "verify" / "latest.json"
    if latest.exists():
        try:
            report = json.loads(latest.read_text(encoding="utf-8"))
            state_id = report.get("state", {}).get("id", "?")
            lines.append(
                f"- Latest verification report `{state_id}`: {report.get('verdict')} "
                f"(generated {report.get('generated_at')}). Treat it as stale unless "
                "`python3 tools/verify.py --check-report reports/verify/latest.json` says CURRENT."
            )
        except (json.JSONDecodeError, OSError):
            lines.append("- Latest verification report unreadable; run `python3 tools/verify.py`.")
    else:
        lines.append("- No verification report yet; run `python3 tools/verify.py --fast` before claiming results.")

    backups = ROOT / ".mutate-backup"
    if backups.is_dir() and any(backups.iterdir()):
        lines.append(
            "- WARNING: .mutate-backup/ is not empty: a mutation run was interrupted and product source may still be "
            "mutated. Tell the owner before doing anything else."
        )

    open_q = len(re.findall(r"^- \*\*Q-\d+", text, re.MULTILINE))
    if open_q:
        lines.append(f"- Open questions in STATUS.md: {open_q}")
    lines.append(
        f"- Rules: work only on increment {increment}; start with `/increment {increment}` (plan first); "
        "numbers in reports come only from tools/verify.py output."
    )
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
