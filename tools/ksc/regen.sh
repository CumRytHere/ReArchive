#!/usr/bin/env bash
# Regenerate every Kaitai parser from specs/*/*.ksy into src/rearchive/generated/ (D-003).
# Uses the pinned npm compiler (no Java). First time: npm ci --prefix tools/ksc
set -euo pipefail
root=$(git rev-parse --show-toplevel)
cd "$root"
[[ -d tools/ksc/node_modules/kaitai-struct-compiler ]] || npm ci --prefix tools/ksc --silent
out=src/rearchive/generated
mkdir -p "$out"
[[ -f "$out/__init__.py" ]] || printf '"""Parsers generated by tools/ksc/regen.sh from specs/*/*.ksy. Do not edit."""\n' > "$out/__init__.py"
shopt -s nullglob
specs=(specs/*/*.ksy)
[[ ${#specs[@]} -gt 0 ]] || { echo "no specs/*/*.ksy found"; exit 0; }
for ksy in "${specs[@]}"; do
  node tools/ksc/ksc.mjs "$ksy" "$out"
done
